import { mkdirSync, writeFileSync } from 'node:fs';
import { runBoth } from '../eval/runner';
import { CHANGE_NOTES, CONFIGS } from '../core/configs';

const out = runBoth();
mkdirSync('results', { recursive: true });
writeFileSync('results/results.json', JSON.stringify({ generatedAt: new Date().toISOString(), configs: CONFIGS, changeNotes: CHANGE_NOTES, ...out }, null, 2));

const pct = (x: number | null) => (x === null ? 'n/a' : (x * 100).toFixed(1) + '%');
const row = (label: string, a: string, b: string) => `| ${label} | ${a} | ${b} |`;
const { metricsA: ma, metricsB: mb, comparison: cmp } = out;
const fail = (rs: typeof out.A) => rs.filter((r) => !r.pass).map((r) => `- **${r.scenarioId}** — ${r.checks.filter((c) => !c.pass).map((c) => `${c.name} (${c.detail})`).join('; ')}`).join('\n') || '- none';
const md = `# Test results (generated by \`npm run eval\`)

Generated ${new Date().toISOString()}. Agents are deterministic rule-based simulators; no LLM, no live call. See README.

| Metric | A (initial) | B (improved) |
|---|---|---|
${row('Scenarios passed', `${ma.passed}/${ma.scenarios} (${pct(ma.passRate)})`, `${mb.passed}/${mb.scenarios} (${pct(mb.passRate)})`)}
${row('Goal reached (completion)', `${ma.goalReached}/${ma.scenarios} (${pct(ma.completionRate)})`, `${mb.goalReached}/${mb.scenarios} (${pct(mb.completionRate)})`)}
${row('Tool call success', `${ma.toolCallsOk}/${ma.toolCalls} (${pct(ma.toolCallSuccessRate)})`, `${mb.toolCallsOk}/${mb.toolCalls} (${pct(mb.toolCallSuccessRate)})`)}
${row('Tool-use checks passed', `${ma.toolChecksPassed}/${ma.toolChecks}`, `${mb.toolChecksPassed}/${mb.toolChecks}`)}
${row('Unsupported-claim incidents', `${ma.incidents} in ${ma.scenariosWithIncidents} scenarios`, `${mb.incidents} in ${mb.scenariosWithIncidents} scenarios`)}
${row('Agent-logic latency mean / p95', `${ma.latencyMeanMs.toFixed(3)} / ${ma.latencyP95Ms.toFixed(3)} ms`, `${mb.latencyMeanMs.toFixed(3)} / ${mb.latencyP95Ms.toFixed(3)} ms`)}

Latency is in-process agent logic only (no speech, network or LLM).

## A → B
- Fixed (${cmp.fixed.length}): ${cmp.fixed.join(', ') || 'none'}
- Still failing in both (${cmp.remaining.length}): ${cmp.remaining.join(', ') || 'none'}
- Regressions (${cmp.regressions.length}): ${cmp.regressions.join(', ') || 'none'}
- Passing in both (${cmp.stillPassing.length}): ${cmp.stillPassing.join(', ') || 'none'}

## Version A failures
${fail(out.A)}

## Version B failures
${fail(out.B)}
`;
writeFileSync('results/RESULTS.md', md);
console.log(md);
